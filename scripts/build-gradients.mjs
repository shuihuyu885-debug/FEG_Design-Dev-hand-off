// Builds tokens/gradients.json and dist/gradients.css from the Figma snapshot
// in source/figma-gradient-styles.json. Node 18+, no dependencies.
//
//   node scripts/build-gradients.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'source/figma-gradient-styles.json');

// Display order. Brand/theme follows the NDS Brand collection mode order.
const BRAND_THEME_ORDER = ['FTN Dark', 'FTN Light', 'CP Light', 'CP Dark', 'PSK Light', 'PSK Dark'];
const TOKEN_ORDER = [
  'gradient', 'overlay-gradient', 'overlay-gradient-primary-on-avatar-edit',
  'mk-ako-card', 'mk-wc-ako-card', 'mk-cas-cs-card', 'mk-card-gradient-1', 'mk-icon-nav-gradient',
];

// Figma gradient start and end points (in the element's 0..1 box) mapped to CSS keywords.
// Keywords follow the element's proportions the same way Figma does, so they match at any size.
const DIRECTIONS = [
  { from: [0.5, 1], to: [0.5, 0], keyword: 'to top', angle: 0 },
  { from: [0, 0.5], to: [1, 0.5], keyword: 'to right', angle: 90 },
  { from: [0.5, 0], to: [0.5, 1], keyword: 'to bottom', angle: 180 },
  { from: [1, 0.5], to: [0, 0.5], keyword: 'to left', angle: 270 },
  { from: [0, 1], to: [1, 0], keyword: 'to top right', angle: 45 },
  { from: [0, 0], to: [1, 1], keyword: 'to bottom right', angle: 135 },
  { from: [1, 0], to: [0, 1], keyword: 'to bottom left', angle: 225 },
  { from: [1, 1], to: [0, 0], keyword: 'to top left', angle: 315 },
];

const fmt = (n) => String(Math.round(n * 1e4) / 1e4);
const hex = ({ r, g, b }) => '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('').toUpperCase();
const slug = (s) => s.toLowerCase().replace(/\s+/g, '-');

// Inverts Figma's gradientTransform to find where the gradient starts and ends in the box.
export function gradientEndpoints([[a, b, c], [d, e, f]]) {
  const det = a * e - b * d;
  const at = (gx, gy) => [(e * (gx - c) - b * (gy - f)) / det, (-d * (gx - c) + a * (gy - f)) / det];
  return { from: at(0, 0.5), to: at(1, 0.5) };
}

export function direction(transform) {
  const { from, to } = gradientEndpoints(transform);
  const near = (p, q) => Math.abs(p[0] - q[0]) < 1e-6 && Math.abs(p[1] - q[1]) < 1e-6;
  const match = DIRECTIONS.find((dir) => near(dir.from, from) && near(dir.to, to));
  if (!match) throw new Error(`Unsupported gradient direction: from ${from} to ${to}. Add a mapping before exporting.`);
  return match;
}

export function cssColor({ r, g, b, a }) {
  return a === 1 ? hex({ r, g, b }) : `rgba(${r}, ${g}, ${b}, ${fmt(a)})`;
}

export function cssGradient(paint) {
  const dir = direction(paint.gradientTransform);
  const stops = paint.gradientStops.map((s) => `${cssColor(s.color)} ${fmt(s.position * 100)}%`).join(', ');
  return `linear-gradient(${dir.keyword}, ${stops})`;
}

function splitDescription(description) {
  const lines = (description || '').split('\n');
  let owner = '';
  if (lines[0] && lines[0].startsWith('KEEP AS STYLE: owner: ')) owner = lines.shift().replace('KEEP AS STYLE: owner: ', '');
  return { owner, text: lines.join('\n').trim() };
}

function sortBy(order) {
  return (x, y) => {
    const i = order.indexOf(x), j = order.indexOf(y);
    return (i < 0 ? order.length : i) - (j < 0 ? order.length : j) || x.localeCompare(y);
  };
}

function build() {
  const snapshot = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const groups = new Map();
  for (const style of snapshot.gradientStyles) {
    const [brandTheme, token] = style.name.split('/');
    if (!token) throw new Error(`Unexpected style name "${style.name}" (expected "<Brand> <Theme>/<token>")`);
    if (style.paints.length !== 1) throw new Error(`${style.name}: expected exactly one paint`);
    const paint = style.paints[0];
    if (paint.type !== 'GRADIENT_LINEAR') throw new Error(`${style.name}: ${paint.type} is not supported yet`);
    if (!paint.visible || paint.opacity !== 1 || paint.blendMode !== 'NORMAL') {
      throw new Error(`${style.name}: paint opacity/visibility/blend mode is not representable in this export`);
    }
    if (!groups.has(brandTheme)) groups.set(brandTheme, new Map());
    groups.get(brandTheme).set(token, style);
  }

  const tokens = {
    $description:
      'NDS gradient tokens. Exported from the Gradient Paint Styles in the canonical NDS Figma library ' +
      `(${snapshot.source.library}, file ${snapshot.source.fileKey}). Grouped by brand and theme. Do not edit by hand.`,
    gradient: {},
  };
  const css = [
    '/*',
    ' * NDS gradients',
    ' * Exported from the Gradient Paint Styles in the canonical NDS Figma library',
    ` * (${snapshot.source.library}, file ${snapshot.source.fileKey}).`,
    ' * Generated by scripts/build-gradients.mjs. Do not edit by hand.',
    ' *',
    ' * Usage: set data-nds-brand and data-nds-theme on a container, then use the variables,',
    ' * e.g. background: var(--nds-gradient-mk-ako-card);',
    ' */',
    '',
  ];

  for (const brandTheme of [...groups.keys()].sort(sortBy(BRAND_THEME_ORDER))) {
    const [brand, theme] = brandTheme.split(' ');
    const group = {};
    css.push(`/* ${brandTheme} */`, `[data-nds-brand="${brand.toLowerCase()}"][data-nds-theme="${theme.toLowerCase()}"] {`);
    const styles = groups.get(brandTheme);
    for (const token of [...styles.keys()].sort(sortBy(TOKEN_ORDER))) {
      const style = styles.get(token);
      const paint = style.paints[0];
      const dir = direction(paint.gradientTransform);
      const value = cssGradient(paint);
      const { owner, text } = splitDescription(style.description);
      group[token] = {
        $type: 'gradient',
        $value: paint.gradientStops.map((s) => ({
          color: {
            colorSpace: 'srgb',
            components: [s.color.r, s.color.g, s.color.b].map((v) => Math.round((v / 255) * 1e4) / 1e4),
            alpha: s.color.a,
            hex: hex(s.color),
          },
          position: s.position,
        })),
        ...(text ? { $description: text } : {}),
        $extensions: {
          'com.feg.nds': {
            kind: 'linear',
            direction: dir.keyword,
            angle: dir.angle,
            css: value,
            owner,
            figmaStyle: style.name,
            figmaStyleKey: style.key,
          },
        },
      };
      css.push(`  --nds-gradient-${token}: ${value};`);
    }
    css.push('}', '');
    tokens.gradient[slug(brandTheme)] = group;
  }

  mkdirSync(join(ROOT, 'tokens'), { recursive: true });
  mkdirSync(join(ROOT, 'dist'), { recursive: true });
  writeFileSync(join(ROOT, 'tokens/gradients.json'), JSON.stringify(tokens, null, 2) + '\n');
  writeFileSync(join(ROOT, 'dist/gradients.css'), css.join('\n'));
  const count = [...groups.values()].reduce((n, g) => n + g.size, 0);
  console.log(`Built ${count} gradients (${groups.size} brand/theme groups) -> tokens/gradients.json, dist/gradients.css`);
  if (snapshot.excludedStyles?.length) console.log(`Skipped ${snapshot.excludedStyles.length} non-gradient paint styles (see snapshot).`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) build();
